report = {
    "status": "PASS",
    "canvas_width_inches": 6.5,
    "body_font_pt": 8.5,
    "tick_font_pt": 8,
    "legend_font_pt": 8,
    "simulations_rerun": False,
    "method": "Capture all original Line2D numeric arrays without saving source figures, then reuse unchanged arrays in new layouts",
    "figures": {},
}


def digest(a):
    return hashlib.sha256(
        np.ascontiguousarray(a, dtype=np.float64).tobytes()
    ).hexdigest()


def validate(fig, olds, mapping, name):
    checks = []
    for ni, oi in enumerate(mapping):
        fresh = fig.axes[ni].lines
        old = olds[oi]["lines"]
        assert len(fresh) == len(old)
        for j, (line, (x, y)) in enumerate(zip(fresh, old)):
            xx = np.asarray(line.get_xdata(), dtype=float)
            yy = np.asarray(line.get_ydata(), dtype=float)
            assert np.array_equal(xx, x, equal_nan=True) and np.array_equal(
                yy, y, equal_nan=True
            )
            checks.append(
                dict(
                    new_axis=ni,
                    source_axis=oi,
                    line=j,
                    points=len(x),
                    x_sha256=digest(x),
                    y_sha256=digest(y),
                )
            )
    report["figures"][name] = {
        "numeric_arrays_identical": True,
        "lines": checks,
        "width_inches": float(fig.get_figwidth()),
        "height_inches": float(fig.get_figheight()),
    }


